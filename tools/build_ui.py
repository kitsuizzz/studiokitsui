#!/usr/bin/env python3
"""Assemble the one self-contained Studio Kitsui page.

    .venv/bin/python tools/build_ui.py            # write ui/index.html
    .venv/bin/python tools/build_ui.py --check    # fail when it is stale

The page is still one file at runtime: app/server.py serves ui/index.html and the
offline tests read it. Only the *sources* are split, under ui/src/:

    ui/src/index.html        the markup (brand regions live here)
    ui/src/css/*.css         tokens, base, the Salon skin, the brand block
    ui/src/js/*.js           numbered slices, concatenated in numeric order

The slices keep the original top-level order. That matters: the script has
top-level state with side effects, so the build must not reorder them. Each
file is a complete run of top-level declarations; do not move a `const` from
one slice to a later one unless you have read ui/README.md.

`--check` is wired into tests/run.sh: editing a source without rebuilding fails
the suite, the same way tests/brand_test.py pins the generated brand regions.
"""

import argparse
import glob
import os
import re
import sys

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
SRC = os.path.join(ROOT, "ui", "src")
OUT = os.path.join(ROOT, "ui", "index.html")
TEMPLATE = os.path.join(SRC, "index.html")
CSS_MARK = "/* build:css */"
JS_MARK = "// build:js"
GENERATED = (
    "<!-- Generated by tools/build_ui.py from ui/src/ — edit the sources,\n"
    "     not this file. Run .venv/bin/python tools/build_ui.py after a change. -->\n"
)


def numbered(path):
    """Sort 10-values.js before 100-agent.js (a plain string sort does not)."""
    m = re.match(r"(\d+)", os.path.basename(path))
    if not m:
        raise SystemExit("ui source has no numeric prefix: " + path)
    return int(m.group(1))


def sources(pattern):
    paths = sorted(glob.glob(os.path.join(SRC, pattern)), key=numbered)
    if not paths:
        raise SystemExit("no ui sources match " + pattern)
    return paths


def read(path):
    with open(path, encoding="utf-8") as f:
        return f.read()


def build():
    template = read(TEMPLATE)
    if template.count(CSS_MARK) != 1 or template.count(JS_MARK) != 1:
        raise SystemExit(
            "ui/src/index.html needs exactly one build marker of each kind"
        )
    css = "".join(read(p) for p in sources("css/*.css"))
    js = "".join(read(p) for p in sources("js/*.js"))
    # The markers sit on their own lines; the sources start with their own
    # header comment, so replace only the marker and keep the template newlines
    # around it (`<style>\n…\n</style>`, `<script>\n…\n</script>`).
    page = template.replace(CSS_MARK, css).replace(JS_MARK, js)
    return page.replace("<!DOCTYPE html>\n", "<!DOCTYPE html>\n" + GENERATED, 1)


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument(
        "--check",
        action="store_true",
        help="verify ui/index.html is up to date instead of writing it",
    )
    args = ap.parse_args()
    page = build()
    if args.check:
        try:
            current = read(OUT)
        except OSError as e:
            raise SystemExit("cannot read %s: %s" % (OUT, e))
        if current == page:
            print("ui/index.html is up to date (%d bytes)" % len(page.encode("utf-8")))
            return 0
        import difflib

        diff = list(
            difflib.unified_diff(
                current.splitlines(),
                page.splitlines(),
                fromfile="ui/index.html (checked in)",
                tofile="ui/index.html (built)",
                lineterm="",
                n=2,
            )
        )
        print("ui/index.html is stale — run .venv/bin/python tools/build_ui.py")
        print("\n".join(diff[:80]))
        if len(diff) > 80:
            print("… %d more diff lines" % (len(diff) - 80))
        return 1
    with open(OUT, "w", encoding="utf-8") as f:
        f.write(page)
    print(
        "wrote ui/index.html (%d bytes) from %d css + %d js sources"
        % (
            len(page.encode("utf-8")),
            len(sources("css/*.css")),
            len(sources("js/*.js")),
        )
    )
    return 0


if __name__ == "__main__":
    sys.exit(main())
